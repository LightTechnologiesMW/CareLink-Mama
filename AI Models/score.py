"""
Score exported cases and produce coordinator priorities.

  python score.py --input data/cases.csv

Writes outputs/case_scores.csv and outputs/case_scores.sql (import the .sql in
phpMyAdmin; re-running is safe, rows are updated in place).
"""
import argparse
import datetime as dt
import json
import os
import re

import joblib
import numpy as np
import pandas as pd

from config import CAT_FEATURES
from features import add_features, load_cases
from safety import priority_tier

REF_RE = re.compile(r"^CL-[0-9A-F]{6}$")


PLAIN = {
    "bin__is_weekend": "weekend report",
    "bin__is_evening": "evening/night report",
    "bin__not_free": "service not free",
    "num__prior_cases": "few earlier contacts",
}
REGIONS = {"1": "Northern", "2": "Central", "3": "Southern"}


def friendly(name, cats):
    if name in PLAIN:
        return PLAIN[name]
    n = name.split("__", 1)[-1]
    for c in cats:
        if n.startswith(c + "_"):
            val = n[len(c) + 1:]
            if c == "region":
                val = REGIONS.get(val, val)
            return f"{c}: {val}"
    return n


def sql_lit(s):
    return "'" + str(s).replace("\\", "\\\\").replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", required=True)
    ap.add_argument("--model-dir", default="models")
    ap.add_argument("--out-dir", default="outputs")
    a = ap.parse_args()

    bundle = joblib.load(os.path.join(a.model_dir, "risk_model.joblib"))
    meta = json.load(open(os.path.join(a.model_dir, "metadata.json")))
    if meta["data_source"] == "synthetic":
        print("*** WARNING: model was trained on SYNTHETIC data. Scores are for testing only. ***\n")

    raw = load = load_cases(a.input)
    df = add_features(raw)
    risk = bundle["pipeline"].predict_proba(df[bundle["cols"]])[:, 1]

    reasons = [""] * len(df)
    if bundle["is_linear"]:
        T = bundle["pipeline"].named_steps["pre"].transform(df[bundle["cols"]])
        contrib = (T - bundle["means"]) * bundle["pipeline"].named_steps["clf"].coef_[0]
        for i in range(len(df)):
            top = np.argsort(-contrib[i])[:3]
            reasons[i] = "; ".join(friendly(bundle["feature_names"][j], CAT_FEATURES)
                                   for j in top if contrib[i][j] > 0.05 and risk[i] >= 0.5)

    out = pd.DataFrame({
        "reference": df["reference"],
        "risk_score": np.round(risk, 3),
        "priority_tier": [priority_tier(u, r) for u, r in zip(df["urgency"], risk)],
        "reasons": reasons,
        "model_source": meta["data_source"],
        "scored_at": dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
    })
    bad = ~out["reference"].astype(str).str.match(REF_RE)
    if bad.any():
        print(f"Skipping {int(bad.sum())} rows with unexpected reference format.")
        out = out[~bad]

    os.makedirs(a.out_dir, exist_ok=True)
    out.to_csv(os.path.join(a.out_dir, "case_scores.csv"), index=False)

    with open(os.path.join(a.out_dir, "case_scores.sql"), "w") as f:
        f.write("-- Generated by score.py. Import in phpMyAdmin after creating case_risk_scores.\n")
        rows = list(out.itertuples(index=False))
        for k in range(0, len(rows), 200):
            vals = ",\n".join(
                f"({sql_lit(r.reference)}, {r.risk_score:.3f}, {sql_lit(r.priority_tier)}, "
                f"{sql_lit(r.reasons[:250])}, {sql_lit(r.model_source)}, {sql_lit(r.scored_at)})"
                for r in rows[k:k + 200])
            f.write("INSERT INTO case_risk_scores (reference, risk_score, priority_tier, reasons, model_source, scored_at) VALUES\n"
                    f"{vals}\nON DUPLICATE KEY UPDATE risk_score=VALUES(risk_score), priority_tier=VALUES(priority_tier), "
                    "reasons=VALUES(reasons), model_source=VALUES(model_source), scored_at=VALUES(scored_at);\n")

    print(out["priority_tier"].value_counts().to_string())
    print(f"\nWrote {len(out)} scores to {a.out_dir}/case_scores.csv and case_scores.sql")


if __name__ == "__main__":
    main()
